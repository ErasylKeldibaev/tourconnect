class Tour {
  final String id;
  final String cityId;
  final String agencyId;
  final String title;
  final String imageUrl;
  final String price;
  final String duration;
  final String description;

  Tour({
    required this.id,
    required this.cityId,
    required this.agencyId,
    required this.title,
    required this.imageUrl,
    required this.price,
    required this.duration,
    required this.description,
  });
}
